def choose_cta(seed, kind="problem"):
    """Academy reels always end with the PLAN keyword (lead). Educational ones: two 'send it to a parent' (reach),
    then one PLAN."""
    mode = os.environ.get("ANIM_CTA", "auto").lower()
    if mode in ("share", "keyword"):
        return mode
    if KINDS[kind]["academy"]:
        return "keyword"
    edu = [r.get("cta") for r in F.recent(40) if r.get("format") == "animated" and r.get("kind") in EDU_KINDS]
    return "keyword" if len(edu) >= 2 and edu[-1] == edu[-2] == "share" else "share"


def _time_label(s, ws, s0, dur):
    """Labels pop on their keyword; wrong fixes get crossed out."""
    hl = {A.norm(h) for h in s.get("highlight") or []}
    hit = next((t for t, w in ws if A.norm(w) in hl), None)
    s["label_at"] = round(max(0.12, min((hit - s0) if hit is not None else 0.3, 0.7)), 2)
    if s.get("strike"):
        s["strike_at"] = round(max(s["label_at"] + 0.7, dur * 0.62), 2)


def _script(kind, seed, use_ai, evergreen_id):
    """-> (script, kind, topic, ctx, used_ai, error). The AI writes it; a pre-written one is always there as a net."""
    err = None
    if use_ai and not evergreen_id and os.environ.get("GEMINI_API_KEY"):
        try:
            sc, topic, ctx = write(kind, seed)
            return sc, kind, topic, ctx, True, None
        except Exception as e:
            err = str(e)[:200]; print(f"animated: AI script ({kind}) failed, using a pre-written one:", err, flush=True)
    for k_ in ([kind] if evergreen_id else [kind, "problem"]):
        try:
            ev_ = evergreen(seed, evergreen_id, k_)
            kind2 = ev_.get("kind") or "problem"
            ctx = {"case": next((c for c in real_cases() if c["id"] == ev_.get("case")), None)}
            sc = validate(ev_, kind2, ctx); sc["id"] = ev_["id"]
            return sc, kind2, None, ctx, False, err
        except Exception as e:
            if evergreen_id or k_ == "problem":
                raise
            print(f"animated: pre-written {k_} script not usable ({str(e)[:120]}); using an educational one", flush=True)


def build(seed, out, kind=None, use_ai=True, evergreen_id=None, cta=None):
    kind = kind if kind in KINDS else "problem"
    if kind == "results" and not real_cases():
        kind = "method"                                # no approved student case to show: talk about how we train
    sc, kind, topic, ctx, used_ai, err = _script(kind, seed, use_ai, evergreen_id)
    case = ctx.get("case") if kind == "results" else None
    cta = cta if cta in ("share", "keyword") else choose_cta(seed, kind)
    body = sc["scenes"]
    end = dict(CTA_SCENE[cta], say=CTA_SAY[cta], params={}, tone="brand")
    scenes = body + [end]
    texts = [s["say"] for s in scenes]
    for i, s in enumerate(scenes):                     # the script in the run log (and in the GitHub summary)
        print(f"  scene {i + 1} [{s['block']}/{(s.get('params') or {}).get('mode', '-')}] {s.get('label', '')!r}: {s['say']}", flush=True)
    summ = os.environ.get("GITHUB_STEP_SUMMARY")
    if summ:
        with open(summ, "a") as f:
            f.write(f"### Guion ({kind}): {sc['title']}\n\n| # | Escena | Rótulo | Voz |\n|---|---|---|---|\n" + "".join(
                f"| {i + 1} | {s['block']} {(s.get('params') or {}).get('mode', '')} | {s.get('label', '')} | {s['say']} |\n"
                for i, s in enumerate(scenes)) + "\n")
    voice_a, words, starts, engine = narrate(texts)
    total = LEAD + len(voice_a) / SR + 1.7
    k = 0
    for i, s in enumerate(scenes):
        n = len(s["say"].split())
        _time_label(s, words[k:k + n], starts[i], (starts[i + 1] if i + 1 < len(scenes) else total) - starts[i])
        k += n
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    tmpd = out.replace(".mp4", "_scenes"); os.makedirs(tmpd, exist_ok=True)
    wav = out.replace(".mp4", "_a.wav")
    track = mix_audio([(voice_a, LEAD)], scenes, starts, total, seed, wav)
    paths = render_scenes(_jobs(scenes, starts, total, words, seed, tmpd))
    join(paths, wav, out)
    os.remove(wav)

    # ---- the cut for TikTok / YouTube / Facebook: "comment PLAN" only works on Instagram, so the ending changes
    alt = None
    if cta == "keyword" and os.environ.get("ALT_ENDING", "on") != "off":
        try:
            c = len(body); nb = sum(len(s["say"].split()) for s in body)
            a_end, w_end = say_extra(CTA_SAY["profile"], like=voice_a)
            cut = _quiet_cut(voice_a, words[nb][0] - LEAD - 0.40, words[nb][0] - LEAD - 0.04)
            va = voice_a[:cut].copy(); r = min(len(va), int(0.04 * SR)); va[-r:] *= np.linspace(1, 0, r)
            at = starts[c] + 0.14
            words2 = words[:nb] + [(at + t, w) for t, w in w_end]
            total2 = at + len(a_end) / SR + 1.7
            end2 = dict(CTA_SCENE["profile"], say=CTA_SAY["profile"], params={}, tone="brand")
            scenes2 = body + [end2]
            _time_label(end2, words2[nb:], starts[c], total2 - starts[c])
            alt = out.replace(".mp4", "_alt.mp4")
            wav2 = alt.replace(".mp4", "_a.wav")
            mix_audio([(va, LEAD), (a_end, at)], scenes2, starts, total2, seed, wav2)
            p2 = render_scenes(_jobs(scenes2, starts, total2, words2, seed, tmpd, tag="x", only={c}))
            join(paths[:c] + p2, wav2, alt)
            os.remove(wav2); os.remove(p2[0])
        except Exception as e:
            alt = None; print("animated: the cut for the other platforms failed (they get the main video):", str(e)[:200], flush=True)
    for p in paths:
        os.remove(p)
    try:
        os.rmdir(tmpd)
    except OSError:
        pass

    send = "Send this to a chess parent who needs it. " if cta == "share" else ""
    cap = F.caption(sc["caption_hook"], sc["caption_body"], send + brand.cta("keyword")["caption"], seed=seed)
    cap_alt = F.caption(sc["caption_hook"], sc["caption_body"], send + "Free training video for parents: link on our profile.", seed=seed)
    open(out.replace(".mp4", ".txt"), "w").write(cap)
    open(out.replace(".mp4", "_alt.txt"), "w").write(cap_alt)
    hook = body[0]["say"]
    F.remember({"format": "animated", "kind": kind, "topic": topic and topic["id"], "evergreen": None if used_ai else sc.get("id"),
                "title": sc["title"], "music": track, "cta": cta, "evidence": sc.get("evidence"), "case": case and case["id"]})
    return {"format": "animated", "kind": kind, "pillar": "academy" if KINDS[kind]["academy"] else "education",
            "engine": "ai" if used_ai else "evergreen", "topic": topic and topic["id"], "story": sc["title"],
            "hook": hook, "headline": body[0]["label"].title(), "blocks": [s["block"] for s in scenes],
            "duration": round(total, 1), "music": track, "cta": cta, "voice_engine": engine, "evidence": sc.get("evidence"),
            "case": case and case["id"], "comment_prompt": sc.get("comment_prompt"), "thumb_offset_ms": 1300,
            "copy_error": err, "hook_options": sc.get("hooks"), "alt_video": alt, "caption_alt": cap_alt}


