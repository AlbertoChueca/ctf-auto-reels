def thud(vol=0.16):
    t = np.arange(int(0.32 * SR)) / SR
    f = 52 + 70 * np.exp(-t * 26)
    return (vol * np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 11)).astype(np.float32)


def mix_audio(voice_a, scenes, starts, total, seed, path):
    n = int(total * SR)
    mix = np.zeros(n, np.float32); speech = np.zeros(n, bool)
    def put(x, at, g=1.0):
        a = int(at * SR)
        if 0 <= a < n:
            b = min(n, a + len(x)); mix[a:b] += g * x[:b - a]
    put(voice_a, LEAD); a0 = int(LEAD * SR); speech[a0:min(n, a0 + len(voice_a))] = np.abs(voice_a[:max(0, n - a0)]) > 0.02
    for i, sc in enumerate(scenes):
        s0 = starts[i]
        if i:
            put(F.swell(0.34, 0.035), s0 - 0.3); put(F.soft_tick(820, 0.05), s0)
        if sc.get("label"):
            lt = s0 + (0.0 if i == 0 else sc.get("label_at", 0.25))
            put(thud(0.13), lt)
            put(F.bell(660 if sc.get("tone") == "bad" else 880, 0.035 if sc.get("tone") == "bad" else 0.05, 0.9), lt + 0.02)
        if sc.get("strike_at"):
            put(F.soft_tick(520, 0.07), s0 + sc["strike_at"])
    bed, track = F.music(total, seed, energy=0.7)
    duck = np.ones(n, np.float32)
    duck[a0:min(n, a0 + len(voice_a) + int(0.25 * SR))] = 0.30
    kk = int(0.2 * SR); duck = np.convolve(duck, np.ones(kk) / kk, "same").astype(np.float32)
    mix += bed[:n] * duck
    F.write_wav(F.master(mix, speech, target_db=-13.5), path)
    return track


