def learned_text():
    """What the account's own results say works (only when views are being measured)."""
    try:
        perf = json.load(open(os.path.join(HERE, "performance.json")))
    except Exception:
        return ""
    rows = [r for r in perf.values() if r.get("views") and r.get("format") == "animated" and r.get("hook")]
    if len(rows) < 6:
        return ""
    def score(r):
        v = max(1, r.get("reach") or r.get("views") or 1)
        return ((r.get("shares") or 0) * 4 + (r.get("saved") or 0) * 3 + (r.get("comments") or 0) * 2 + (r.get("likes") or 0)) / v
    rows.sort(key=score, reverse=True)
    best = "; ".join(f"\"{r['hook']}\"" for r in rows[:3]); worst = "; ".join(f"\"{r['hook']}\"" for r in rows[-2:])
    return (f"WHAT OUR OWN AUDIENCE SHARES AND SAVES MOST (first lines of our best reels): {best}.\n"
            f"What they ignored: {worst}. Learn from the difference; do not copy.")




