# ----------------------------------------------------------------------- narration: one take, timed word by word
_NUM = {"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five", "6": "six", "7": "seven", "8": "eight",
        "9": "nine", "10": "ten", "12": "twelve", "15": "fifteen", "20": "twenty", "30": "thirty"}


def _tok(w):
    w = A.norm(w)
    return _NUM.get(w, w)


def _resample(a, sr_from, tempo=1.0):
    """Pitch-preserving tempo change + resample to the mix rate (ffmpeg atempo)."""
    p = subprocess.run(["ffmpeg", "-v", "error", "-f", "f32le", "-ar", str(sr_from), "-ac", "1", "-i", "-",
                        "-af", f"atempo={tempo:.3f}", "-ar", str(SR), "-ac", "1", "-f", "f32le", "-"],
                       input=a.astype(np.float32).tobytes(), capture_output=True)
    return np.frombuffer(p.stdout, np.float32).copy()


def _one_take(texts):
    """Continuous narration from Gemini, verified. Returns (audio@voiceSR, [(t, word)] per script word) or None."""
    import voice
    key = os.environ.get("GEMINI_API_KEY")
    if not key or os.environ.get("VOICE_ENGINE", "gemini").lower() == "kokoro":
        return None
    if voice._asr(np.zeros(voice.SR // 2, np.float32)) is None:
        return None                                    # cannot verify a long take without speech recognition
    script = "\n\n".join(texts)
    words = script.split()
    want = [_tok(w) for w in words]
    for attempt in range(2):
        try:
            take = voice._trim(voice._gemini_call(script, key))
        except Exception as e:
            print("animated voice: take failed:", str(e)[:150], flush=True); continue
        heard = voice._asr(take) or []
        got = [_tok(w) for w, _, _ in heard]
        sm = difflib.SequenceMatcher(None, want, got, autojunk=False)
        t = [None] * len(want); m_h = []
        for i, j, n in sm.get_matching_blocks():
            for d in range(n):
                t[i + d] = heard[j + d][1]; m_h.append(j + d)
        cover = sum(v is not None for v in t) / max(1, len(want))
        extra = len(got) - len(m_h)
        print(f"animated voice: one take {len(take) / voice.SR:.1f}s, {cover:.0%} of the script heard, {extra} other words", flush=True)
        if cover < 0.86 or not m_h:
            continue
        j0, j1 = min(m_h), max(m_h)
        inside_extra = sum(1 for j in range(j0, j1 + 1) if j not in set(m_h))
        if inside_extra > max(3, 0.08 * len(want)):
            continue
        a0 = max(0.0, heard[j0][1] - 0.10); a1 = min(len(take) / voice.SR, heard[j1][2] + 0.30)
        audio = take[int(a0 * voice.SR):int(a1 * voice.SR)].copy()
        known = [(i, v - a0) for i, v in enumerate(t) if v is not None]
        xs = [-1] + [i for i, _ in known] + [len(want)]
        ys = [0.0] + [v for _, v in known] + [len(audio) / voice.SR]
        tt = list(np.interp(range(len(want)), xs, ys))
        ends = sorted((heard[j][2] - a0) for j in m_h)
        # shorten long silences (keep the performance, lose the dead air)
        cuts, gaps = [], []
        hs = [(heard[j][1] - a0, heard[j][2] - a0) for j in range(j0, j1 + 1)]
        for (s0, e0), (s1, e1) in zip(hs[:-1], hs[1:]):
            if s1 - e0 > 0.62:
                cuts.append((e0 + 0.26, s1 - 0.22))
        keep = np.ones(len(audio), bool); fade = np.ones(len(audio), np.float32)
        r = int(0.012 * voice.SR)
        for c0, c1 in cuts:
            i0, i1 = int(c0 * voice.SR), int(c1 * voice.SR)
            keep[i0:i1] = False
            fade[max(0, i0 - r):i0] *= np.linspace(1, 0, min(r, i0)); fade[i1:i1 + r] *= np.linspace(0, 1, len(fade[i1:i1 + r]))
        audio = (audio * fade)[keep]
        def shift(x):
            return x - sum(min(c1, max(c0, x)) - c0 for c0, c1 in cuts)
        tt = [shift(x) for x in tt]
        n_in = min(len(audio) // 4, int(0.01 * voice.SR)); audio[:n_in] *= np.linspace(0, 1, n_in)
        n_out = min(len(audio) // 4, int(0.05 * voice.SR)); audio[-n_out:] *= np.linspace(1, 0, n_out)
        for i in range(1, len(tt)):
            tt[i] = max(tt[i], tt[i - 1] + 0.04)
        voice.ENGINE_USED = "gemini"
        return audio, list(zip(tt, words))
    return None


def narrate(texts):
    """-> (audio at SR, words [(t, word)] on the reel clock, scene start times, voice engine)."""
    import voice
    voice.reset()
    res = _one_take(texts)
    if res is not None:
        audio, words = res
        engine = "gemini-one-take"
    else:                                              # line by line (Gemini with its own checks, or the local voice)
        clips = voice.say_many(texts, speed=1.06, styles=[None] * len(texts), one_take=False)
        gap = int(0.16 * voice.SR)
        parts, words, pos = [], [], 0
        for c, tx in zip(clips, texts):
            c = c[:max(1, len(c) - int(0.08 * voice.SR))]
            for ts, w in voice.align(c, tx):
                words.append((pos / voice.SR + ts, w))
            parts += [c, np.zeros(gap, np.float32)]; pos += len(c) + gap
        audio = np.concatenate(parts)
        engine = voice.ENGINE_USED or "local"
    a48 = _resample(audio, voice.SR, TEMPO)
    words = [(LEAD + t / TEMPO, w) for t, w in words]
    starts, k = [], 0
    for tx in texts:
        starts.append(max(0.0, words[k][0] - 0.14) if k < len(words) else (starts[-1] + 2.5 if starts else 0.0))
        k += len(tx.split())
    starts[0] = 0.0
    for i in range(1, len(starts)):
        starts[i] = max(starts[i], starts[i - 1] + 1.2)
    return F.vo_compress(a48), words, starts, engine


# ----------------------------------------------------------------------- render: one process per scene
ENC = ["-c:v", "libx264", "-preset", "veryfast", "-profile:v", "high", "-crf", "19", "-pix_fmt", "yuv420p", "-r", str(FPS),
       "-g", str(FPS * 2), "-bf", "2", "-threads", "2"]


def _render_scene(job):
    i, sc, f0, f1, s0, d, sd, words, chunks, path = job
    tmp = path.replace(".mp4", ".part.mp4")
    proc = subprocess.Popen(["ffmpeg", "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "bgr0", "-s", f"{A.W}x{A.H}",
                             "-r", str(FPS), "-i", "-"] + ENC + [tmp], stdin=subprocess.PIPE)
    k = A.K()
    for f in range(f0, f1):
        tg = f / FPS
        B.draw_scene(k, sc, tg - s0, d, sd, words, chunks, tg, first=(i == 0))
        proc.stdin.write(k.bytes())
    proc.stdin.close()
    if proc.wait() != 0:
        raise RuntimeError(f"ffmpeg failed on scene {i}")
    os.replace(tmp, path)
    return path


def render(scenes, starts, total, words, seed, out, audio_wav):
    import multiprocessing as mp
    chunks = A.chunk_words(words)
    tmpd = out.replace(".mp4", "_scenes"); os.makedirs(tmpd, exist_ok=True)
    jobs = []
    for i, sc in enumerate(scenes):
        s0 = starts[i]; s1 = starts[i + 1] if i + 1 < len(scenes) else total
        jobs.append((i, sc, int(round(s0 * FPS)), int(round(s1 * FPS)), s0, s1 - s0, seed + i * 7, words, chunks,
                     os.path.join(tmpd, f"s{i:02d}.mp4")))
    n = max(1, min(len(jobs), int(os.environ.get("RENDER_PROCS", os.cpu_count() or 2))))
    t0 = time.time()
    if n > 1:
        with mp.get_context("fork").Pool(n) as pool:
            paths = pool.map(_render_scene, jobs, chunksize=1)
    else:
        paths = [_render_scene(j) for j in jobs]
    lst = os.path.join(tmpd, "list.txt")
    open(lst, "w").write("".join(f"file '{os.path.abspath(p)}'\n" for p in paths))
    tmp = out.replace(".mp4", ".part.mp4")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", lst, "-i", audio_wav,
                    "-map", "0:v", "-map", "1:a", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-ar", "48000", "-ac", "2",
                    "-shortest", "-movflags", "+faststart", "-use_editlist", "0", tmp], check=True)
    os.replace(tmp, out)
    for p in paths + [lst]:
        os.remove(p)
    os.rmdir(tmpd)
    print(f"animated: rendered {int(total * FPS)} frames in {time.time() - t0:.0f}s with {n} processes", flush=True)


