"""Animated explainer reels: neon figures that SHOW what the narrator says (the format parents stop for).

SEVEN KINDS OF REEL, one visual language:
  education (about 80 %)  problem   a painful situation -> what is really going on -> what to do
                          myth      a belief many parents hold -> the truth -> what to do instead
                          science   one real study, told simply -> what it means for a chess kid
                          howto     "what to do when..." in three concrete steps
                          question  a real question parents ask us -> an honest answer
  the academy (about 20 %) method   how ChessTalentsFactory trains (diagnosis, the 3-part class, levels, reports...)
                          results   a real student's progress + proven numbers (only approved claims and cases)

How it is made
- The AI writes the script and picks, for every sentence, a scene BLOCK from a fixed catalog (anim_blocks.py).
  Blocks are drawn in code: figures, boards, charts, clocks... nothing is generated by an image model.
- ONE continuous narration (natural rhythm). Speech recognition gives the time of every word, so the scenes cut
  and the captions light up exactly on the voice. Any word that is not in the script is cut out.
- Scenes render in parallel straight into ffmpeg, then they are joined without re-encoding. When the ending says
  "comment PLAN" (Instagram's DM bot), a second cut with the ending "link on our profile" is made for TikTok,
  YouTube and Facebook, re-using every other scene.
- Honest by construction: numbers must be approved (claims.json, cases.json), research only from evidence_bank.json,
  no person's name, no book.

python make_animated.py [evergreen-id] [seed] [share|keyword]   -> out/test_animated_<id>.mp4 (no key needed)
"""
