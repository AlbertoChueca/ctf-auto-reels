# ----------------------------------------------------------------------- validation
_NUMWORD = r"\b(?:one|two|three|four|five|six|seven|eight|nine|ten|twenty|thirty|forty|fifty|hundreds?|thousands?)\b"


def _w(s): return len(str(s).split())
def _short(s, n): return " ".join(str(s or "").split()[:n])


def validate(sc):
    scenes = [s for s in (sc.get("scenes") or []) if str(s.get("say", "")).strip()]
    if not 5 <= len(scenes) <= 9:
        raise ValueError("need 6 to 8 scenes")
    ev = evidence()
    eid = sc.get("evidence") if sc.get("evidence") in ev else None
    out, prev = [], None
    for i, s in enumerate(scenes):
        say = re.sub(r"\[[^\]]*\]|\([^)]*\)|[*_#`]", " ", str(s["say"]))
        say = re.sub(r"\s+", " ", say).strip()
        if not 4 <= _w(say) <= 26:
            raise ValueError(f"scene {i + 1}: narration must be 9-20 words, got {_w(say)}")
        blk = s.get("block")
        if blk not in CATALOG:
            raise ValueError(f"scene {i + 1}: unknown block '{blk}'")
        spec, p = CATALOG[blk][1], {}
        raw = s.get("params") or {}
        sig = (blk, raw.get("mode"), raw.get("tone"))
        if sig == prev:
            raise ValueError(f"scene {i + 1}: same picture as the scene before; vary the visuals")
        prev = sig
        for key, kind in spec.items():
            v = raw.get(key)
            if isinstance(kind, list):
                p[key] = v if v in kind else kind[0]
            elif kind == "text" and v:
                p[key] = _short(v, 9)
            elif kind == "list" and isinstance(v, list):
                p[key] = [_short(x, 5) for x in v if str(x).strip()][:3]
            elif kind == "int" and v is not None:
                try: p[key] = int(float(v))
                except Exception: pass
            elif kind == "float" and v is not None:
                try: p[key] = max(0.05, min(1.0, float(v)))
                except Exception: pass
        if blk == "tiles":
            p["n"] = max(4, min(30, p.get("n", 20))); p["k"] = max(1, min(p["n"], p.get("k", p["n"])))
        label = _short(s.get("label"), 4).upper()[:24]
        hl = [h for h in (s.get("highlight") or []) if isinstance(h, str) and A.norm(h) and
              A.norm(h) in {A.norm(x) for x in say.split()}][:2]
        out.append({"say": say, "block": blk, "params": p, "label": label, "tone": s.get("tone") if s.get("tone") in TONES else "brand",
                    "highlight": hl, "strike": bool(s.get("strike"))})
    words = sum(_w(s["say"]) for s in out)
    if not 60 <= words <= 135:
        raise ValueError(f"total narration is {words} words; it must be 85-120")
    if len({s["block"] for s in out}) < min(4, len(out)):
        raise ValueError("use at least 5 different blocks")
    blob = " ".join(s["say"] for s in out)
    if not eid and re.search(r"\b(stud(y|ies)|research(ers)?|experiments?|scientists?|psychologists?|science (shows|says)|"
                             r"experts? (say|agree)|proven|data shows?|statistic(s|ally)?|percent)\b|%", blob, re.I):
        raise ValueError("it mentions research or statistics without an approved 'evidence' id; remove it or cite one from the list")
    if eid:                                            # the cited study gets its real chart and source line
        tgt = next((s for s in out if s["block"] == "bars"), None)
        if tgt is None:
            cands = [s for s in out[1:] if re.search(r"stud|research|found|scientist", s["say"], re.I)] or [out[min(4, len(out) - 1)]]
            tgt = cands[0]; tgt["block"] = "bars"
        tgt["params"] = dict(ev[eid]["viz"]["params"], source_text=ev[eid]["source_text"])
    texts = [blob, sc.get("caption_hook", ""), sc.get("caption_body", ""), sc.get("comment_prompt", "")]
    for s in out:
        texts += [s["label"]] + [str(v) for k_, v in s["params"].items() if k_ != "source_text" and isinstance(v, str)] + \
                 [str(x) for v in s["params"].values() if isinstance(v, list) for x in v]
    if eid:                                            # only the numbers that appear in the approved finding are allowed
        src = ev[eid]["finding"] + " " + json.dumps(ev[eid]["viz"])
        ok_nums = set(re.findall(r"\d[\d,]*", src)) | {w.lower() for w in re.findall(_NUMWORD, src, flags=re.I)}
        def allow(m):
            return " " if m.group(0).lower().rstrip("+") in ok_nums else m.group(0)
        texts = [re.sub(r"\d[\d,]*\+?|" + _NUMWORD, allow, t, flags=re.I) for t in texts]
    F.check_text(texts)
    return {"title": _short(sc.get("title") or out[0]["label"].title(), 8), "evidence": eid, "scenes": out,
            "caption_hook": _short(sc.get("caption_hook") or out[0]["say"], 14),
            "caption_body": str(sc.get("caption_body") or "").strip(),
            "comment_prompt": _short(sc.get("comment_prompt") or "", 16), "hooks": sc.get("hooks")}


def evergreen(seed, eid=None):
    lib = json.load(open(EVERGREEN))
    if eid:
        return json.loads(json.dumps(next(x for x in lib if x["id"] == eid)))
    used = {r.get("evergreen"): i for i, r in enumerate(F.recent(400)) if r.get("evergreen")}
    return json.loads(json.dumps(min(lib, key=lambda x: (used.get(x["id"], -1), random.Random(seed).random()))))


def learned_text():
    """What the account's own results say works (only when views are being measured)."""
    try:
        perf = json.load(open(os.path.join(HERE, "performance.json")))
    except Exception:
        return ""
    rows = [r for r in perf.values() if r.get("views") and r.get("format") == "animated" and r.get("hook")]
    if len(rows) < 6:
        return ""
    def score(r):
        v = max(1, r.get("reach") or r.get("views") or 1)
        return ((r.get("shares") or 0) * 4 + (r.get("saved") or 0) * 3 + (r.get("comments") or 0) * 2 + (r.get("likes") or 0)) / v
    rows.sort(key=score, reverse=True)
    best = "; ".join(f"\"{r['hook']}\"" for r in rows[:3]); worst = "; ".join(f"\"{r['hook']}\"" for r in rows[-2:])
    return (f"WHAT OUR OWN AUDIENCE SHARES AND SAVES MOST (first lines of our best reels): {best}.\n"
            f"What they ignored: {worst}. Learn from the difference; do not copy.")


