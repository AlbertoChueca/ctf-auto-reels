def evidence(only_approved=True):
    try:
        fs = json.load(open(EVIDENCE))["facts"]
    except Exception:
        return {}
    return {f["id"]: f for f in fs if f.get("approved") or not only_approved}


def pick_evidence(n=3, seed=0):
    """The n approved studies used least recently (so the same study never comes back for weeks)."""
    ev = evidence()
    used = {r.get("evidence"): i for i, r in enumerate(F.recent(400)) if r.get("evidence")}
    rng = random.Random(seed)
    ids = sorted(ev, key=lambda k: (used.get(k, -1), rng.random()))[:n]
    return {k: ev[k] for k in ids}


def approved_claims():
    return {c["id"]: c for c in guard.approved() if c["id"] in CLAIM_VIZ}


_W2D = {"two": "2", "three": "3", "four": "4", "five": "5", "six": "6"}


def real_cases():
    """Approved student cases with a clear 'from X to Y in Z' progress, one per distinct story."""
    out, seen = [], set()
    for c in guard.cases():
        blob = (c.get("text") or "") + " ; " + " ; ".join(c.get("facts") or [])
        m = re.search(r"from\s+(\d{3,4})\s+to\s+(over\s+)?(\+)?(\d{3,4})(\+)?(?:\s*\(?rating\)?)?[^.;]*?\bin\s+(?:only\s+|just\s+)?"
                      r"((?:\d+|two|three|four|five|six)\s+(?:months|years))", blob, re.I)
        if not m:
            continue
        span = re.sub(r"^(two|three|four|five|six)", lambda x: _W2D[x.group(1).lower()], m.group(6).lower())
        key = (m.group(1), m.group(4), span)
        if key in seen:
            continue
        seen.add(key)
        ms = []
        for f in (c.get("facts") or []) + re.split(r"(?<=[.;)])\s*(?=[A-Z0-9])", c.get("text") or ""):
            f = re.sub(r"^\s*[\d, ]{4,}(\(Age \d+\))?\s*:\s*", "", f).replace(" .", "").strip(" .")
            f = re.sub(r"\s+", " ", f)
            if re.search(r"\bfrom\s+\d{3,4}\s+to\b|stuck at|started", f, re.I) or not 2 <= len(f.split()) <= 9:
                continue
            if A.norm(f) not in {A.norm(x) for x in ms}:
                ms.append(f)
        out.append({"id": c["id"], "frm": int(m.group(1)), "to": int(m.group(4)), "plus": bool(m.group(2) or m.group(3) or m.group(5)),
                    "span": span, "milestones": ms[:6], "blob": blob, "name": c.get("name") or ""})
    return out


def pick_case(seed=0):
    cs = real_cases()
    if not cs:
        return None
    used = {r.get("case"): i for i, r in enumerate(F.recent(400)) if r.get("case")}
    rng = random.Random(seed)
    return min(cs, key=lambda c: (used.get(c["id"], -1), rng.random()))


def catalog_text(kind):
    out = []
    for name, (desc, params) in CATALOG.items():
        if name in ACADEMY_BLOCKS and not KINDS[kind]["academy"]:
            continue
        if name == "case" and kind != "results":
            continue
        ps = ", ".join(f"{k}: {'|'.join(v) if isinstance(v, list) else v}" for k, v in params.items())
        out.append(f"- {name}: {desc}. params {{{ps}}}")
    return "\n".join(out)


