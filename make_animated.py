"""Animated explainer reels: neon figures that SHOW what the narrator says (the format parents stop for).

One reel = hook scene -> the real problem -> the usual wrong fix -> why it happens -> (real research) ->
what to do tonight -> one-line reframe -> ending (send it to another chess parent / comment PLAN).

How it is made
- The AI writes the script and picks, for every sentence, a scene BLOCK from a fixed catalog (anim_blocks.py).
  Blocks are drawn in code: figures, boards, charts, clocks... nothing is generated by an image model.
- ONE continuous narration (natural rhythm). Speech recognition gives the time of every word, so the scenes cut
  and the captions light up exactly on the voice. Any word that is not in the script is cut out.
- Scenes render in parallel (one process per CPU) straight into ffmpeg, then they are joined without re-encoding.
- Honest by construction: numbers must be approved, research can only come from evidence_bank.json.

python make_animated.py [evergreen-id]   -> out/test_animated.mp4 (works without any key: local voice)
"""
