def choose_cta(seed):
    mode = os.environ.get("ANIM_CTA", "auto").lower()
    if mode in CTA_SAY:
        return mode
    return "share" if (seed // 24) % 3 != 2 else "keyword"       # 2 of 3 days ask for the send (reach), 1 of 3 for PLAN


def build(seed, out, use_ai=True, evergreen_id=None, cta=None):
    topic, sc, used_ai, err = None, None, False, None
    if use_ai and not evergreen_id and os.environ.get("GEMINI_API_KEY"):
        try:
            custom = (os.environ.get("TOPIC_OVERRIDE") or "").strip()
            topic = ({"id": "custom", "q": custom, "angle": "Decide the honest, practical answer a top youth coach would give."}
                     if custom else F.pick_topic("animated", seed))
            sc = write(topic, seed); used_ai = True
        except Exception as e:
            err = str(e)[:200]; print("animated: AI script failed, using a pre-written one:", err, flush=True)
    if sc is None:
        ev_ = evergreen(seed, evergreen_id)
        sc = validate(ev_); sc["id"] = ev_["id"]
    cta = cta or choose_cta(seed)
    scenes = sc["scenes"] + [{"say": CTA_SAY[cta], "block": "share" if cta == "share" else "plan", "params": {},
                              "label": CTA_LABEL[cta], "tone": "brand", "highlight": ["parent"] if cta == "share" else [brand.KEYWORD.lower()]}]
    texts = [s["say"] for s in scenes]
    for i, s in enumerate(scenes):                     # the script in the run log (and in the GitHub summary)
        print(f"  scene {i + 1} [{s['block']}/{(s.get('params') or {}).get('mode', '-')}] {s.get('label', '')!r}: {s['say']}", flush=True)
    summ = os.environ.get("GITHUB_STEP_SUMMARY")
    if summ:
        with open(summ, "a") as f:
            f.write(f"### Guion: {sc['title']}\n\n| # | Escena | Rótulo | Voz |\n|---|---|---|---|\n" + "".join(
                f"| {i + 1} | {s['block']} {(s.get('params') or {}).get('mode', '')} | {s.get('label', '')} | {s['say']} |\n"
                for i, s in enumerate(scenes)) + "\n")
    voice_a, words, starts, engine = narrate(texts)
    total = LEAD + len(voice_a) / SR + 1.7
    k = 0
    for i, s in enumerate(scenes):                     # labels pop on their keyword; wrong fixes get crossed out
        n = len(s["say"].split()); ws = words[k:k + n]; k += n
        hl = {A.norm(h) for h in s.get("highlight") or []}
        hit = next((t for t, w in ws if A.norm(w) in hl), None)
        s["label_at"] = round(max(0.12, min((hit - starts[i]) if hit is not None else 0.3, 0.7)), 2)
        dur = (starts[i + 1] if i + 1 < len(scenes) else total) - starts[i]
        if s.get("strike"):
            s["strike_at"] = round(max(s["label_at"] + 0.7, dur * 0.62), 2)
    wav = out.replace(".mp4", "_a.wav")
    track = mix_audio(voice_a, scenes, starts, total, seed, wav)
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    render(scenes, starts, total, words, seed, out, wav)
    os.remove(wav)
    send = "Send this to a chess parent who needs it. " if cta == "share" else ""
    cap = F.caption(sc["caption_hook"], sc["caption_body"], send + brand.cta("keyword")["caption"], seed=seed)
    open(out.replace(".mp4", ".txt"), "w").write(cap)
    hook = sc["scenes"][0]["say"]
    F.remember({"format": "animated", "topic": topic and topic["id"], "evergreen": None if used_ai else sc.get("id"),
                "title": sc["title"], "music": track, "cta": cta})
    return {"format": "animated", "engine": "ai" if used_ai else "evergreen", "topic": topic and topic["id"], "story": sc["title"],
            "hook": hook, "headline": sc["scenes"][0]["label"].title(), "blocks": [s["block"] for s in scenes],
            "duration": round(total, 1), "music": track, "cta": cta, "voice_engine": engine, "evidence": sc.get("evidence"),
            "comment_prompt": sc.get("comment_prompt"), "thumb_offset_ms": 1300, "copy_error": err,
            "hook_options": sc.get("hooks")}


